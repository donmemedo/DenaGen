def interpret(genotypes: dict) -> list:
    out = []
    for t in TRAITS:
        g = "".join(sorted(genotypes.get(t["rsid"], "")))
        hit = t["map"].get(g)
        out.append({k: t[k] for k in ("id", "rsid", "gene", "icon", "en", "fa")} | {
            "genotype": g or None,
            "result": {"en": hit[0], "fa": hit[1], "level": hit[2]} if hit else None,
        })
    return out


def parse_raw(text: str) -> dict:
    per_chrom = dict.fromkeys(CHROMOSOMES, 0)
    total = no_calls = het = 0
    build = None
    wanted = {t["rsid"] for t in TRAITS}
    found = {}
    for line in text.splitlines():
        if not line or line[0] == "#":
            if "build 37" in line.lower() or "grch37" in line.lower():
                build = "GRCh37"
            elif "build 38" in line.lower() or "grch38" in line.lower():
                build = "GRCh38"
            continue
        parts = line.split("\t") if "\t" in line else line.split()
        if len(parts) < 4 or parts[0] == "rsid":
            continue
        rsid, chrom, _, g = parts[:4]
        chrom = {"23": "X", "24": "Y", "25": "X", "26": "MT", "M": "MT"}.get(chrom, chrom)
        if chrom not in per_chrom:
            continue
        total += 1
        per_chrom[chrom] += 1
        if "-" in g or "0" in g:
            no_calls += 1
            continue
        if len(g) == 2 and g[0] != g[1]:
            het += 1
        if rsid in wanted:
            found[rsid] = g
    called = total - no_calls
    return {
        "total": total,
        "called": called,
        "no_calls": no_calls,
        "call_rate": round(100 * called / total, 2) if total else 0,
        "heterozygosity": round(100 * het / called, 2) if called else 0,
        "build": build,
        "chromosomes": [{"name": c, "snps": n} for c, n in per_chrom.items()],
        "traits": interpret(found),
    }


def sample_raw(seed: int = 23, n: int = 8000, genotypes: dict | None = None) -> str:
    """Synthetic file in 23andMe format, for trying the analyzer without real data."""
    r = random.Random(seed)
    # approximate relative chromosome sizes (Mb)
    sizes = [249, 243, 198, 191, 181, 171, 159, 146, 141, 136, 135, 133, 115, 107, 102, 90, 83, 80, 59, 64, 47, 51, 155, 57, 1]
    lines = ["# This data file generated by Risheh (synthetic sample) at: 2026-01-01",
             "# We are using reference human assembly build 37 (also known as Annotation Release 104).",
             "# rsid\tchromosome\tposition\tgenotype"]
    pairs = ["AG", "CT", "AC", "GT", "AT", "CG"]
    for chrom, size in zip(CHROMOSOMES, sizes):
        for i in range(max(3, n * size // 3100)):
            a, b = r.choice(pairs)
            g = r.choice([a + a, a + b, b + b, a + b, a + a]) if r.random() > 0.01 else "--"
            if chrom in ("Y", "MT"):
                g = g[0] if g != "--" else "-"
            lines.append(f"rs{r.randint(1000, 99999999)}\t{chrom}\t{(i + 1) * size * 1000 + r.randint(0, 999)}\t{g}")
    for t in TRAITS:
        g = (genotypes or {}).get(t["rsid"]) or r.choice(list(t["map"]))
        lines.append(f"{t['rsid']}\t1\t1\t{g}")
    return "\n".join(lines) + "\n"
